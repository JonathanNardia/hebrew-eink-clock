"""Generate HebrewClock/hebrew_words.h: one pre-shaped 1-bit bitmap per vocalized word.

Every Hebrew string literal in HebrewClock.ino is split into words; each word is
shaped with HarfBuzz (so nikud lands in the right place) and rasterized with
FreeType. The firmware then only lays whole words out right-to-left.

Run:  python tools/make_words.py   (needs: pip install uharfbuzz freetype-py pillow numpy)
"""
from pathlib import Path
import re
import numpy as np
from PIL import Image
from shape import Shaper

FONT = 'C:/Windows/Fonts/davidbd.ttf'
MAX_LINE_WIDTH = 900      # of 960
LINE_GAP = 24             # vertical gap between the two lines
MAX_PX = 140

root = Path(__file__).resolve().parent.parent
sketch = root / 'HebrewClock'
src = (sketch / 'HebrewClock.ino').read_text(encoding='utf-8')


def literals(name):
    body = re.search(r'\b' + name + r'\[\]\s*=\s*\{(.*?)\};', src, re.S).group(1)
    return re.findall(r'"([^"]*)"', body)


units, teens, tens, hours = (literals(n) for n in ('unitsV', 'teensV', 'tensV', 'hours'))
exact = re.search(r'EXACT\s*=\s*"([^"]*)"', src).group(1)


def minute_words(m):
    if m == 0:
        return exact
    if m < 10:
        return units[m]
    if m < 20:
        return teens[m - 10]
    return tens[m // 10] + (' ' + units[m % 10] if m % 10 else '')


all_literals = [s for s in re.findall(r'"([^"]*)"', src) if re.search('[\u05d0-\u05ea]', s)]
lines = sorted(set(all_literals) | {minute_words(m) for m in range(60)} | set(hours))
words = sorted({w for line in lines for w in line.split()})


def render_all(px):
    sh = Shaper(FONT, px)
    out = {w: sh.render(w) for w in words}
    space = round(px * 0.28)
    return out, space


def ink_rows(out):
    top, bottom = 10 ** 9, 0
    for canvas, _, _ in out.values():
        rows = np.where((canvas >= 128).any(axis=1))[0]
        top, bottom = min(top, rows[0]), max(bottom, rows[-1])
    return top, bottom + 1


def line_width(out, space, line):
    ws = line.split()
    return sum(out[w][1] for w in ws) + space * (len(ws) - 1)


# Largest size where every line fits the width and two lines fit the height.
for px in range(MAX_PX, 40, -2):
    out, space = render_all(px)
    top, bottom = ink_rows(out)
    height = bottom - top
    widest = max(line_width(out, space, l) for l in lines)
    if widest <= MAX_LINE_WIDTH and 2 * height + LINE_GAP <= 530:
        break
print(f'font px={px}, word height={height}, widest line={widest}px, {len(words)} words')

parts = ['#pragma once', '// Generated by tools/make_words.py - do not edit by hand.', '#include <Arduino.h>',
         'struct HebrewWord { const char *text; const uint8_t *data; uint16_t width; uint16_t advance; };',
         f'constexpr int WORD_HEIGHT = {height};', f'constexpr int SPACE_WIDTH = {space};',
         f'constexpr int LINE_GAP = {LINE_GAP};']
table = []
preview_words = {}
for i, w in enumerate(words):
    canvas, advance, _ = out[w]
    bits = canvas[top:bottom] >= 128
    cols = np.where(bits.any(axis=0))[0]
    # Keep the pen origin at x=0 so word spacing follows the font's advances.
    width = max(advance, int(cols[-1]) + 1)
    bits = bits[:, :width]
    if bits.shape[1] < width:
        bits = np.pad(bits, ((0, 0), (0, width - bits.shape[1])))
    packed = np.packbits(bits.flatten())
    parts.append(f'const uint8_t word_{i}[] PROGMEM = {{' + ','.join(map(str, packed)) + '};')
    table.append(f'{{"{w}", word_{i}, {width}, {advance}}},')
    preview_words[w] = (bits, advance)
parts.append('const HebrewWord HEBREW_WORDS[] = {')
parts += table
parts.append('};')
parts.append('constexpr size_t HEBREW_WORD_COUNT = sizeof(HEBREW_WORDS) / sizeof(HEBREW_WORDS[0]);')
(sketch / 'hebrew_words.h').write_text('\n'.join(parts) + '\n', encoding='utf-8')


# Preview mirrors the firmware layout exactly.
def draw(img, line, y):
    total = line_width(out, space, line)
    right = (960 + total) // 2
    for w in line.split():
        bits, adv = preview_words[w]
        right -= adv
        region = Image.fromarray(np.where(bits, 0, 255).astype('uint8'))
        img.paste(region, (right, y), Image.fromarray((bits * 255).astype('uint8')))
        right -= space


top1 = (540 - 2 * height - LINE_GAP) // 2
preview = Image.new('L', (960, 540), 255)
draw(preview, hours[9], top1)
draw(preview, minute_words(21), top1 + height + LINE_GAP)
preview.save(sketch / 'preview.png')

sheet = Image.new('L', (960 * 2, 540 * 2), 200)
for k, (h, m) in enumerate([(12, 0), (2, 38), (11, 15), (8, 57)]):
    img = Image.new('L', (960, 540), 255)
    draw(img, hours[h % 12], top1)
    draw(img, minute_words(m), top1 + height + LINE_GAP)
    sheet.paste(img, ((k % 2) * 960, (k // 2) * 540))
sheet.save(root / 'docs' / 'preview_sheet.png')
print('Wrote hebrew_words.h, preview.png, preview_sheet.png')
